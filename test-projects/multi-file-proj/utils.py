"""Utility functions for the multi-file project."""


def add(a: int, b: int) -> int:
    """Return sum of two numbers."""
    return a + b


def multiply(a: int, b: int) -> int:
    """Return product of two numbers."""
    return a * b


def greet(name: str) -> str:
    """Return a greeting message."""
    return f"Hello, {name}!"
